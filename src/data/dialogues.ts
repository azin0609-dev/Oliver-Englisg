import type { CategoryId, Dialogue, Difficulty } from '../types';
import { categoryById } from './categories';
type Turn = [string, string];
function dialogue(
  category: CategoryId,
  number: number,
  english: string,
  traditionalChinese: string,
  difficulty: Difficulty,
  turns: Turn[],
): Dialogue {
  return {
    id: `dialogue-${category}-${number}`,
    category,
    difficulty,
    english,
    traditionalChinese,
    parentTip: categoryById[category].tip,
    suggestedReply: turns[1][0],
    tags: [category, traditionalChinese, english],
    turns: turns.map(([english, traditionalChinese], i) => ({
      role: i % 2 === 0 ? 'parent' : 'child',
      english,
      traditionalChinese,
    })),
  };
}
